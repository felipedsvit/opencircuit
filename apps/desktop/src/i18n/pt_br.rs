//! The Brazilian Portuguese catalog: the English text, then its translation.
//! Sorted by the English text, with no repeated key (a test checks it).

/// The translation of `text`, if the catalog has one.
pub(super) fn lookup(text: &str) -> Option<&'static str> {
    CATALOG
        .binary_search_by_key(&text, |(english, _)| english)
        .ok()
        .and_then(|at| CATALOG.get(at))
        .map(|(_, translation)| *translation)
}

